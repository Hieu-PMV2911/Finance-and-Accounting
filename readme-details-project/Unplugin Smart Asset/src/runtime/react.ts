import { createElement, type ReactElement } from 'react';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export interface SmartIconProps {
  /** icon key, e.g. `lucide-home` */
  name: string;
  className?: string;
  style?: Record<string, string | number>;
  title?: string;
  'aria-label'?: string;
  width?: number | string;
  height?: number | string;
}

function attr(key: string): string {
  return `#smart-icon-${key}`;
}

/**
 * `<use>`-based icon for frameworks where the tag syntax is unavailable
 * (Next.js with Turbopack, SSR layouts, tests).
 */
export function SmartIcon(props: SmartIconProps): ReactElement {
  const { name, className, style, title, width = '1em', height = '1em' } = props;
  const label = props['aria-label'];
  const a11y = label
    ? { 'aria-label': label, role: 'img' as const }
    : { 'aria-hidden': true, focusable: 'false' };

  return createElement(
    'svg',
    {
      className,
      style,
      width,
      height,
      viewBox: '0 0 24 24',
      ...a11y,
      dangerouslySetInnerHTML: {
        __html: (title ? `<title>${title}</title>` : '') + `<use href="${attr(name)}" />`,
      },
    },
  );
}

export interface SmartAssetSpriteProps {
  /** Path to the sprite generated by `smart-asset prepare`. */
  src?: string;
}

/**
 * Renders the sprite once, on the server. Use it in the root layout of SSR
 * frameworks, where no HTML injection hook exists.
 */
export function SmartAssetSprite({ src }: SmartAssetSpriteProps = {}): ReactElement {
  const file = resolve(process.cwd(), src ?? 'sprite.svg');
  if (!existsSync(file)) {
    throw new Error(
      `[smart-asset] sprite not found at ${file}. Run "npx smart-asset prepare" before building.`,
    );
  }
  return createElement('div', {
    'aria-hidden': true,
    suppressHydrationWarning: true,
    dangerouslySetInnerHTML: { __html: readFileSync(file, 'utf8') },
  });
}
